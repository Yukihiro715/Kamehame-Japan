/** Stored in the existing enquiry notes so the team, acknowledgement and ledger receive it. */
export function golfPlanningNotes(data: Record<string, string>): string {
  return [
    data.golf_budget && `Budget per golfer: ${data.golf_currency || "JPY"} ${data.golf_budget} (booking fee, golf, rentals and extras included; transport: ${data.golf_budget_transport || "unsure"})`,
    data.golf_journey && `Maximum one-way journey: ${data.golf_journey}`,
    data.golf_equipment && `Equipment / shoe sizing system: ${data.golf_equipment}`,
    data.message,
  ].filter(Boolean).join("\n");
}
